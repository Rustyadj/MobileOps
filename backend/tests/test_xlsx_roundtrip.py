ROUND_TRIP_FIELDS = ("name", "category", "qr_code", "sku", "model", "serial_number", "condition", "location",
                     "quantity", "available", "daily_rate", "tracking_type", "notes", "equipment_family")


async def export_bytes(env, dataset, role="admin", fmt="xlsx", **filters):
    ds = exports.resolve_dataset(dataset)
    docs = await env.db[ds.source].find(ds.query(exports.clean_filters(ds, filters)), {"_id": 0}).sort(*ds.sort).to_list(None)
    docs = [server.redact_money_for_crew(d, role) for d in docs]
    return exports.render_xlsx(ds, docs, role, brand="Concrete Form", generated_by="Tester", filters=filters), docs


def sheet_rows(content: bytes, name="Data"):
    ws = load_workbook(io.BytesIO(content))[name]
    return [[c.value for c in row] for row in ws.iter_rows()]


async def test_xlsx_is_formatted_and_typed(env):
    content, docs = await export_bytes(env, "equipment")
    wb = load_workbook(io.BytesIO(content))
    assert wb.sheetnames == ["Data", "Report Info"]
    ws = wb["Data"]
    assert ws.freeze_panes == "A2" and ws.auto_filter.ref.startswith("A1:")
    assert ws["A1"].font.bold and ws["A1"].fill.fgColor.rgb.endswith("1F2937")
    header = [c.value for c in ws[1]]
    rate_col = header.index("Daily Rate") + 1
    qty_col = header.index("Owned") + 1
    assert ws.cell(2, rate_col).number_format == "#,##0.00"
    assert isinstance(ws.cell(2, qty_col).value, int), "numbers must stay numeric, not text"
    info = dict(sheet_rows(content, "Report Info"))
    assert info["Records"] == len(docs) and info["Dataset"] == "equipment" and info["Generated by"] == "Tester"


async def test_crew_xlsx_has_no_money_columns_or_values(env):
    content, _ = await export_bytes(env, "equipment", role="crew")
    rows = sheet_rows(content)
    assert "Daily Rate" not in rows[0]
    assert not any(isinstance(v, float) and v in (12.5, 8.0, 1.5) for r in rows[1:] for v in r)
    consumables, _ = await export_bytes(env, "consumables", role="crew")
    assert "Cost" not in sheet_rows(consumables)[0] and "Price" not in sheet_rows(consumables)[0]


@pytest.mark.parametrize("dataset,filters,column,expected", [
    ("tools", {}, "Name", {"Hammer Drill", "Circular Saw", "Broken Grinder", "Dominick Level"}),
    ("damaged", {}, "Name", {"Strongback 8ft", "Broken Grinder"}),
    ("assignments", {}, "Tool", {"Hammer Drill", "Dominick Level"}),
    ("assignments", {"checked_out_to": "nick"}, "Tool", {"Hammer Drill"}),  # word-start, case-insensitive: not "Dominick"
    ("equipment", {"category": "strongback"}, "Name", {"Strongback 8ft"}),
    ("consumables", {}, "Product", {"Foam Adhesive"}),
    ("block", {}, "Product", {"ICF Block 8in"}),
    ("shop_tasks", {"assignee": "nick"}, "Task", {"Sharpen blades"}),
    ("returns", {}, "ID", {"d2-cccccccc"[:8]}),
    ("outbound", {}, "ID", {"d1-bbbbbbbb"[:8]}),
])
async def test_new_datasets_select_the_right_records(env, dataset, filters, column, expected):
    content, _ = await export_bytes(env, dataset, **filters)
    rows = sheet_rows(content)
    idx = rows[0].index(column)
    assert {r[idx] for r in rows[1:]} == expected, rows


