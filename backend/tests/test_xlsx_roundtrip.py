async def test_formula_text_is_stored_inert_and_round_trips(env):
    evil = "=HYPERLINK(\"http://evil\",\"x\")"
    await env.db.equipment.update_one({"qr_code": "Q-101"}, {"$set": {"notes": evil}})
    content, _ = await export_bytes(env, "equipment")
    ws = load_workbook(io.BytesIO(content))["Data"]
    notes_col = [c.value for c in ws[1]].index("Notes") + 1
    cells = [ws.cell(r, notes_col) for r in range(2, ws.max_row + 1)]
    hit = next(c for c in cells if c.value == evil)
    assert hit.data_type == "s", "text beginning with '=' must not become a formula"
    # and the importer reads it back as the same literal text, not a formula error
    fresh = AsyncMongoMockClient()["fresh"]
    preview = await data_imports.stage_import(fresh, dataset="equipment", filename="e.xlsx", content=content, actor_id="boss", actor_name="Boss")
    assert preview["summary"]["error"] == 0
    row = next(r for r in (await fresh.import_jobs.find_one({"id": preview["import_id"]}))["rows"] if r["data"]["name"] == "Circular Saw")
    assert row["data"]["notes"] == evil


async def test_export_then_import_into_empty_database_reproduces_every_record(env):
    content, docs = await export_bytes(env, "equipment")
    target = AsyncMongoMockClient()["target"]
    preview = await data_imports.stage_import(target, dataset="equipment", filename="inv.xlsx", content=content, actor_id="boss", actor_name="Boss")
    assert preview["summary"] == {"total": len(docs), "create": len(docs), "update": 0, "unchanged": 0, "skip_duplicate": 0, "error": 0}
    assert not preview["blocking_errors"]
    result = await data_imports.commit_import(target, server, import_id=preview["import_id"], plan_hash=preview["plan_hash"], actor_id="boss", actor_name="Boss")
    assert result["result"]["created"] == len(docs)
    imported = {d["sku"]: d for d in await target.equipment.find({}, {"_id": 0}).to_list(None)}
    for original in docs:
        copy = imported[original["sku"]]
        for field in ROUND_TRIP_FIELDS:
            assert (copy.get(field) or None) == (original.get(field) or None), f"{original['name']}.{field}"
    # initial stock goes through the ledger exactly like POST /equipment does
    entries = await target.ledger_entries.find({}, {"_id": 0}).to_list(None)
    assert sum(e["qty"] for e in entries) == sum(d["available"] for d in docs)
    assert all(e["reason"] == "received" for e in entries)


async def test_reimporting_an_unchanged_export_changes_nothing(env):
    content, docs = await export_bytes(env, "equipment")
    before = await snapshot(env.db, *DOMAIN)
    preview = await data_imports.stage_import(env.db, dataset="equipment", filename="inv.xlsx", content=content, actor_id="boss", actor_name="Boss")
    assert preview["summary"]["skip_duplicate"] == len(docs) and preview["summary"]["create"] == 0 and preview["summary"]["error"] == 0
    job = await env.db.import_jobs.find_one({"id": preview["import_id"]})
    assert all(not r["diff"] for r in job["rows"]), "an unchanged export must show zero differences"
    assert await snapshot(env.db, *DOMAIN) == before
    update_preview = await data_imports.stage_import(env.db, dataset="equipment", filename="inv.xlsx", content=content, actor_id="boss", actor_name="Boss", on_duplicate="update")
    assert update_preview["summary"]["unchanged"] == len(docs) and update_preview["summary"]["update"] == 0


async def test_consumables_round_trip(env):
    content, docs = await export_bytes(env, "consumables")
    target = AsyncMongoMockClient()["t2"]
    preview = await data_imports.stage_import(target, dataset="consumables", filename="c.xlsx", content=content, actor_id="boss", actor_name="Boss")
    await data_imports.commit_import(target, server, import_id=preview["import_id"], plan_hash=preview["plan_hash"], actor_id="boss", actor_name="Boss")
    item = await target.sellable_items.find_one({"product": "Foam Adhesive"}, {"_id": 0})
    assert item["kind"] == "consumable" and item["quantity_on_hand"] == 12 and item["cost"] == 5.0 and item["price"] == 9.0
